DROP TABLE IF EXISTS "delay_events";
DROP TABLE IF EXISTS "flights";
DROP TABLE IF EXISTS "airlines";

CREATE TABLE "airlines" (
    "CODE" VARCHAR(3) PRIMARY KEY,
    "NAME" VARCHAR(100) NOT NULL
);

CREATE TABLE "flights" (
    "ID" BIGINT PRIMARY KEY,
    "FLIGHT_NUMBER" VARCHAR(50) NOT NULL,
    "AIRLINE_CODE" VARCHAR(3) NOT NULL REFERENCES "airlines" ("CODE"),
    "DEPARTURE_AIRPORT" VARCHAR(3) NOT NULL,
    "ARRIVAL_AIRPORT" VARCHAR(3) NOT NULL,
    "SCHEDULED_TIME" TIMESTAMP NOT NULL
);

CREATE INDEX idx_flights_airline_code ON "flights" ("AIRLINE_CODE");

CREATE TABLE "delay_events" (
    "ID" BIGINT PRIMARY KEY,
    "FLIGHT_ID" BIGINT NOT NULL REFERENCES "flights" ("ID"),
    "STATUS" VARCHAR(20) NOT NULL,
    "DELAY_MINUTES" INT,
    "ACTUAL_TIME" TIMESTAMP,
    "RECORDED_AT" TIMESTAMP NOT NULL
);

CREATE INDEX idx_delay_events_flight_recorded_at ON "delay_events" ("FLIGHT_ID", "RECORDED_AT");
